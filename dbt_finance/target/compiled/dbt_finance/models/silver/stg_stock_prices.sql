WITH deduplicated AS (
    SELECT 
        UPPER(TRIM(TICKER)) AS TICKER,
        TRADE_DATE,
        ROUND(OPEN_PRICE, 4) AS OPEN_PRICE,
        ROUND(HIGH_PRICE, 4) AS HIGH_PRICE,
        ROUND(LOW_PRICE, 4) AS LOW_PRICE,
        ROUND(CLOSE_PRICE, 4) AS CLOSE_PRICE,
        VOLUME,
        INGESTED_AT,
        ROW_NUMBER() OVER (
            PARTITION BY UPPER(TRIM(TICKER)), TRADE_DATE 
            ORDER BY INGESTED_AT DESC
        ) AS rn
    FROM FINANCE_LAKEHOUSE.BRONZE.STOCK_PRICES_RAW
    WHERE CLOSE_PRICE IS NOT NULL AND CLOSE_PRICE > 0
)

SELECT 
    TICKER,
    TRADE_DATE,
    OPEN_PRICE,
    HIGH_PRICE,
    LOW_PRICE,
    CLOSE_PRICE,
    VOLUME,
    ROUND(
        (CLOSE_PRICE - LAG(CLOSE_PRICE) OVER (PARTITION BY TICKER ORDER BY TRADE_DATE)) 
        / NULLIF(LAG(CLOSE_PRICE) OVER (PARTITION BY TICKER ORDER BY TRADE_DATE), 0) * 100, 
    4) AS DAILY_RETURN_PCT,
    INGESTED_AT
FROM deduplicated
WHERE rn = 1